LANGS = ['en', 'hi', 'mr', 'es', 'fr', 'de']
ANCHOR = re.compile(r'^(\s*)pfLoadFailed:.*,$', re.M)


def block(indent: str, lang_idx: int) -> str:
    lines = []
    for key, *vals in KEYS:
        lines.append(f'{indent}{key}: {vals[lang_idx]},')
    return '\n'.join(lines)


total = 0
for i, lang in enumerate(LANGS):
    path = BASE / f'{lang}.ts'
    src = path.read_text(encoding='utf-8')
    if re.search(r'^\s*pfGoogleAccount:', src, re.M):
        print(f'{lang}: keys already present — skipping')
        continue
    m = ANCHOR.search(src)
    assert m, f'{lang}: pfLoadFailed anchor not found'
    replacement = m.group(0) + '\n' + block(m.group(1), i)
    src = src[:m.start()] + replacement + src[m.end():]
    path.write_text(src, encoding='utf-8')
    total += len(KEYS)
    print(f'{lang}: inserted {len(KEYS)} keys after pfLoadFailed')

print(f'DONE — {total} keys written across {len(LANGS)} files')
